"""weights.npz -> integer memory files for Vivado ($readmemh) + a bit-exact integer reference model.
Run in the RC folder after training. Needs: weights.npz, strokes.csv, make_dataset.py, train_cnn.py.
Writes the folder  export/ :
  conv1_w.mem conv1_b.mem conv2_w.mem conv2_b.mem fc_w.mem fc_b.mem   (hex, one value per line)
  quant_params.vh                                                       (requantisation constants)
  test_images.mem test_expected.mem                                     (self-test vectors for the RTL)
  report.txt
Scheme: int8 weights (one scale per layer), binary input, uint8 activations, int32 accumulators/biases,
requantise with  out = clip((acc * M + 2^(SH-1)) >> SH, 0, 255)  after ReLU.
"""
import os, numpy as np
from train_cnn import load_strokes, make_images

OUT, SH = 'export', 20
os.makedirs(OUT, exist_ok=True)
W = np.load('weights.npz')
w1, b1, w2, b2, w3, b3 = (W[k].astype(np.float64) for k in ('0_weight', '0_bias', '3_weight', '3_bias', '8_weight', '8_bias'))
names = [str(n) for n in W['labels']]

def conv(x, w):                                   # x (C,H,W) -> (O,H,W), 3x3, pad 1, works for float or int
    xp = np.pad(x, ((0, 0), (1, 1), (1, 1)))
    win = np.lib.stride_tricks.sliding_window_view(xp, (3, 3), axis=(1, 2))
    return np.einsum('chwij,ocij->ohw', win, w)

def pool(x):
    c, h, wd = x.shape
    return x.reshape(c, h // 2, 2, wd // 2, 2).max(axis=(2, 4))

# ---- float pass over the real strokes: activation ranges + float predictions ----
strokes, y, _ = load_strokes()
X, Y = make_images(strokes, y, np.arange(len(y)))
X = X[:, 0].astype(np.int64)                      # N x 16 x 16, values 0/1
def fwd_float(img):
    a1 = pool(np.maximum(conv(img[None].astype(float), w1) + b1[:, None, None], 0))
    a2 = pool(np.maximum(conv(a1, w2) + b2[:, None, None], 0))
    return a1, a2, w3 @ a2.reshape(-1) + b3
res = [fwd_float(i) for i in X]
a1max = max(r[0].max() for r in res); a2max = max(r[1].max() for r in res)
pf = np.array([r[2].argmax() for r in res])

# ---- quantise ----
s1, s2, s3 = (np.abs(w).max() / 127 for w in (w1, w2, w3))
sa1, sa2 = a1max / 255, a2max / 255
q8 = lambda w, s: np.clip(np.round(w / s), -127, 127).astype(np.int64)
w1q, w2q, w3q = q8(w1, s1), q8(w2, s2), q8(w3, s3)
b1q = np.round(b1 / s1).astype(np.int64)                 # input scale is 1 (binary image)
b2q = np.round(b2 / (s2 * sa1)).astype(np.int64)
b3q = np.round(b3 / (s3 * sa2)).astype(np.int64)
m1 = int(round(s1 / sa1 * 2 ** SH)); m2 = int(round(s2 * sa1 / sa2 * 2 ** SH))
assert 0 < m1 < 2 ** 31 and 0 < m2 < 2 ** 31, "multiplier out of range"

def requant(acc, m):
    return np.clip((np.maximum(acc, 0) * m + (1 << (SH - 1))) >> SH, 0, 255)

def fwd_int(img):
    a1 = requant(pool(conv(img[None], w1q) + b1q[:, None, None]), m1)
    a2 = requant(pool(conv(a1, w2q) + b2q[:, None, None]), m2)
    return w3q @ a2.reshape(-1) + b3q, a1, a2
ints = [fwd_int(i) for i in X]
pi = np.array([r[0].argmax() for r in ints])
peak = max(int(np.abs(r[0]).max()) for r in ints)

# ---- write memory files ----
def hexw(v, bits): return format(int(v) & ((1 << bits) - 1), '0%dx' % (bits // 4))
def wmem(name, arr, bits):
    open(f'{OUT}/{name}.mem', 'w').write('\n'.join(hexw(v, bits) for v in arr.reshape(-1)) + '\n')
wmem('conv1_w', w1q, 8); wmem('conv1_b', b1q, 32)
wmem('conv2_w', w2q, 8); wmem('conv2_b', b2q, 32)
wmem('fc_w', w3q, 8);    wmem('fc_b', b3q, 32)
open(f'{OUT}/quant_params.vh', 'w').write(
    f"// generated by export_weights.py\n`define NUM_CLASSES {len(names)}\n`define REQ_SHIFT {SH}\n"
    f"`define REQ_MULT1 {m1}\n`define REQ_MULT2 {m2}\n")
# test vectors: up to 3 strokes per class; pixel p = row*16 + col is bit p of a 256-bit word
sel = [i for c in range(len(names)) for i in np.where(Y == c)[0][:3]]
open(f'{OUT}/test_images.mem', 'w').write('\n'.join(
    format(sum(int(b) << p for p, b in enumerate(X[i].reshape(-1))), '064x') for i in sel) + '\n')
open(f'{OUT}/test_expected.mem', 'w').write('\n'.join(hexw(pi[i], 8) for i in sel) + '\n')

rep = [f"classes (output index -> name): {dict(enumerate(names))}",
       f"layer sizes: conv1_w {w1q.size}, conv2_w {w2q.size}, fc_w {w3q.size} values",
       f"weight scales {s1:.5f} {s2:.5f} {s3:.5f}; activation scales {sa1:.5f} {sa2:.5f}",
       f"REQ_SHIFT {SH}, REQ_MULT1 {m1}, REQ_MULT2 {m2}",
       f"int8 weight range used: conv1 [{w1q.min()},{w1q.max()}] conv2 [{w2q.min()},{w2q.max()}] fc [{w3q.min()},{w3q.max()}]",
       f"largest |logit| {peak} (needs {int(peak).bit_length() + 1} bits signed)",
       f"float accuracy {np.mean(pf == Y):.3f} | integer-model accuracy {np.mean(pi == Y):.3f} | agreement {np.mean(pf == pi) * 100:.1f}%"]
open(f'{OUT}/report.txt', 'w').write('\n'.join(rep) + '\n'); print('\n'.join(rep)); print(f"\nfiles written to {OUT}/")